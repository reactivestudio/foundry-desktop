/// Порт запуска одного рана агента — вендор-нейтральная абстракция, от которой
/// зависит `RunStore` (практики 03: сторы получают сервисы через init, протокольные
/// сервисы дают мокабельность для тестов и превью). Порт не называет вендора: за
/// ним стоит любой агент. Сегодня единственная реализация — `ClaudeRunner` в
/// Infrastructure; завтра рядом встанут другие. Тесты подставляют фейк со
/// скриптованными событиями, не запуская подпроцесс.
///
/// Порт живёт в доменном ядре (Domain), а не рядом с реализацией: правило
/// зависимостей Clean Architecture требует, чтобы абстракцией владел внутренний
/// слой, а конкретику внедряли снаружи из корня композиции. Так `RunStore` зависит
/// только от Core и ничего не знает ни о вендоре, ни о Subprocess/Infrastructure.
public protocol AgentRunner: Sendable {
    func stream(
        prompt: String,
        projectDirectory: String,
        permissionMode: PermissionMode
    ) -> AsyncThrowingStream<AgentEvent, Error>
}
