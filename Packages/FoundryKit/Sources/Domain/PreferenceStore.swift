/// Порт durable-настроек. `RunStore` — доменная модель — не должен сам
/// дотягиваться до `UserDefaults.standard`: чтение и запись пользовательских
/// флагов инвертированы в этот порт, а продакшн-адаптер (обёртка над
/// `UserDefaults`) внедряется из корня композиции. Тест подставляет in-memory
/// фейк и не трогает глобальные настройки процесса.
///
/// Bool-only и по строковому ключу намеренно: сегодня хранится ровно один флаг,
/// а форма повторяет семантику `UserDefaults` (nil = ключ не задан → домен сам
/// применяет дефолт), чтобы адаптер был тонким и без трансляции.
public protocol PreferenceStore {
    /// Значение флага по ключу; `nil` — ключ ещё не сохранён.
    func bool(forKey key: String) -> Bool?
    /// Сохранить значение флага под ключом.
    func setBool(_ value: Bool, forKey key: String)
}
