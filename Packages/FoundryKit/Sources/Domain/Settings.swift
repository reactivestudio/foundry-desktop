/// Пользовательские настройки приложения как единый доменный объект. Сегодня
/// durable-настройка ровно одна — импортировать ли сессию рана во внешний
/// просмотрщик; тип структурирован под рост: новые настройки станут полями рядом,
/// каждая со своим дефолтом. Значения задаются с дефолтами при создании, поэтому
/// объект всегда в валидном состоянии, а дефолт живёт в одном месте — здесь, в
/// домене (адаптер хранилища лишь переопределяет поле, если ключ уже сохранён).
public struct Settings: Sendable, Equatable {
    /// Импортировать сессию рана во внешний просмотрщик (сегодня — Claude Code
    /// Desktop, deep link claude://resume). Дефолт — включено: смысл фичи в
    /// наблюдении рана из просмотрщика.
    public var opensSessionInViewer: Bool

    public init(opensSessionInViewer: Bool = true) {
        self.opensSessionInViewer = opensSessionInViewer
    }
}
