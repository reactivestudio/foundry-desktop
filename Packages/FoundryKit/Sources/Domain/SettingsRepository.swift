/// Порт репозитория пользовательских настроек: загрузка и сохранение агрегата
/// `Settings` как целого. Presentation не дотягивается до `UserDefaults.standard` —
/// читает и меняет настройки через сценарий Application поверх этого порта, а
/// продакшн-адаптер (обёртка над `UserDefaults`) внедряется корнем композиции. Тест
/// подставляет in-memory фейк и не трогает глобальные настройки процесса.
public protocol SettingsRepository {
    /// Текущие настройки; несохранённые ключи берут доменный дефолт из `Settings`.
    func load() -> Settings
    /// Сохранить настройки целиком.
    func save(_ settings: Settings)
}
