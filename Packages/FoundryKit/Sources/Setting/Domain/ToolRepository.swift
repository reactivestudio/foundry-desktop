/// Порт репозитория сущности `Tool`: загрузка и сохранение её как целого.
/// Presentation не дотягивается до `UserDefaults.standard` — читает и меняет
/// настройки через сценарий Application поверх этого порта, а продакшн-адаптер
/// (обёртка над `UserDefaults`) внедряется корнем композиции. Тест подставляет
/// in-memory фейк и не трогает глобальные настройки процесса.
public protocol ToolRepository {
    /// Текущие настройки инструментов; несохранённые ключи берут доменный дефолт
    /// из `Tool`.
    func load() -> Tool
    /// Сохранить настройки инструментов целиком.
    func save(_ tool: Tool)
}
