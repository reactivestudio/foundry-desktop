/**
 Способность копить и выпускать доменные события — общий словарь тактического DDD.
 Корень, реализующий `Dispatchable`, накапливает события своих изменений (`record`), а
 use-case по завершении транзакции забирает их (`releaseEvents`) и публикует наружу
 (Infra → Application). Диспетчеризация в шину — забота диспетчера, не корня: корень
 лишь ОТДАЁТ события. `AnyObject` — способность имеет мутабельное состояние (очередь),
 поэтому только для ссылочных типов (агрегатов).
 */
public protocol Dispatchable: AnyObject {
    /// Уже накопленные, но ещё не выпущенные события (только чтение).
    var domainEvents: [DomainEvent] { get }

    /// Записать доменное событие; зовётся самим корнем при значимом изменении.
    func record(event: DomainEvent)

    /// Выпустить накопленные события и очистить очередь.
    func releaseEvents() -> [DomainEvent]
}
