/**
 Проверка инвариантов на ВЕСЬ корень сразу: вешает `@Invariant` на каждую его команду и
 на инициализаторы. Пишется на классе, когда правило одно на всех, — тогда его нельзя
 забыть на новой команде. Это местный аналог AOP: не рантайм-перехват, как в Spring, а
 переписывание тел на компиляции.

 Команду от запроса отличает CQS, и это не эвристика, а требование: команда ничего не
 возвращает (tell-don't-ask), запрос ничего не меняет. Отсюда правила отбора:

 - метод без возвращаемого значения → команда, проверка вставляется;
 - метод с возвращаемым значением → запрос, не трогаем (лишняя проверка была бы безвредна —
   инвариант чист и идемпотентен, — но и бессмысленна);
 - метод, который И возвращает, И присваивает состоянию → ошибка компиляции: разделить по
   CQS либо, если разделить нельзя, пометить `@Invariant` руками;
 - `private`/`fileprivate` и `static` пропускаются: приватные — внутренняя механика
   команды, статические — фабрики, у которых ещё нет `self`;
 - сами методы проверки пропускаются, иначе проверка вызвала бы себя: `checkInvariants`,
   метод с этой же аннотации и любой, названный в `@Invariant(check:)` на команде класса;
   плюс `hash(into:)` — служебный `Hashable`, а не команда;
 - метод с уже проставленной руками `@Invariant` не трогается — своя аннотация старше
   классовой, так на одной команде живёт проверка, отличная от общей.

 Ограничение, о котором надо знать: мутация, спрятанная в приватный хелпер, синтаксисом не
 видна, поэтому «метод с возвратом, который меняет состояние через хелпер» диагностика не
 поймает. Это остаточный риск, который закрывает CQS на ревью, а не макрос.
 */
@attached(memberAttribute)
public macro Invariants() = #externalMacro(module: "CoreMacros", type: "InvariantsMacro")

/**
 То же на весь корень, но нестандартным методом проверки: `@Invariants(check: "checkNaming")`
 — им и будут помечены все команды класса.

 Почему имя строкой, хотя на команде `@Invariant(check:)` берёт типизированную ссылку:
 ссылка на метод обязана упомянуть сам класс (`Rack.checkNaming`), а чтобы её разрешить,
 компилятору нужно сначала раскрыть макрос, висящий на этом классе, — получается
 «circular reference resolving attached macro». Внутри класса цикла нет, поэтому макрос
 сам собирает типизированный вызов `Тип.метод` и ставит его командам: опечатка в имени
 даёт обычную ошибку компиляции «у типа нет такого члена», а не молчание.
 */
@attached(memberAttribute)
public macro Invariants(check: String) =
    #externalMacro(module: "CoreMacros", type: "InvariantsMacro")
