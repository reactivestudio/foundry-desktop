/**
 Аналог котлиновского `check(cond)` — КОНТРАКТ кода: «этого не может быть». Пара к
 `require(correct:orThrow:)`, и разница между ними не в строгости, а в том, кто виноват
 при нарушении:

 - `require` — виноваты ДАННЫЕ (пустое имя, мусор в хранилище). Это штатный сценарий,
   ради которого приложение и написано → восстановимо, `throws` доменной ошибкой,
   доезжает до UI. Место — фабрики VO: невалидным VO существовать не должен.
 - `check` — виноват КОД: вызывающий позвал команду, которую в этом состоянии звать
   нельзя (предусловие), либо сам агрегат после команды оказался противоречивым
   (инвариант, см. `checkInvariants`). Восстанавливаться не от чего → падаем.

 Именно `precondition`, а не `assert`: контракт обязан держаться и в релизной сборке.
 Отсюда цена — инвариант зовётся на КАЖДОЙ команде агрегата, поэтому тяжёлые проверки
 (обход больших коллекций, IO) в него не кладут. `@autoclosure` на сообщении — собираем
 текст лениво, только когда правило уже нарушено.
 */
public func check(correct condition: Bool, orFail message: @autoclosure () -> String = "") {
    precondition(condition, message())
}
