 Корень агрегата — общий словарь тактического DDD. Граница согласованности и
 единственная точка входа изменений (снаружи в части агрегата не лезут в обход него).
 Плоский вариант — БЕЗ доменных событий; агрегатам, которым события нужны, служит
 наследник `DispatchingAggregateRoot` (протокол `Dispatchable`).

