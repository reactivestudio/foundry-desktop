 базовый — пустой no-op), а зовётся он не руками в теле, а аннотацией — body-макрос
 дописывает в команду `defer { checkInvariants() }`. Это местный аналог AOP: не
 рантайм-перехват, как в Spring, а переписывание тела на компиляции. Форм две, и обе
 принимают метод проверки:

 - `@Invariants` на классе — правило на весь корень, вешается на все его команды и
   инициализаторы разом, поэтому на новой команде проверку не забыть;
 - `@Invariant` на команде — точечно, когда правило нужно ей одной; на классе с
   `@Invariants` она старше классовой и перебивает её (скажем, своей проверкой).

 `open`-класс, напрямую не инстанцируется по соглашению. Один тип — один файл.
 */
