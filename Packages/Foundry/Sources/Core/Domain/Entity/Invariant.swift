/**
 Проверка инвариантов на выходе из ОДНОЙ команды — body-макрос, дописывающий в её тело
 `defer { checkInvariants() }`. Ставится точечно, когда проверка нужна не всему корню, а
 конкретному методу; правило на весь корень пишут классовой `@Invariants`, и та же
 аннотация на команде её перебивает (например, чтобы задать команде свою проверку).

 Что даёт `defer`: он регистрируется первым стейтментом, а выполняется на выходе — то есть
 проверка идёт после ВСЕХ изменений команды, а не между ними (иначе команда, меняющая две
 группы разом, падала бы на собственном промежуточном состоянии), и переживает ранние
 `return`. На выброшенной ошибке проверка тоже сработает — намеренно: если команда бросила
 посреди изменения, полусостояние обязано быть поймано.

 Работает и на инициализаторе — так корень не родится невалидным.
 */
@attached(body)
public macro Invariant() = #externalMacro(module: "CoreMacros", type: "InvariantMacro")

/**
 Та же проверка, но нестандартным методом: `@Invariant(check: Preference.checkNaming)`.
 Аргумент — ссылка на метод, а не строка с выражением: его типизирует компилятор, и
 переименование метода не оставляет за собой мёртвую аннотацию. В тело подставляется имя,
 вызов идёт на `self`.

 Осторожно с семантикой: правило, справедливое лишь после ОДНОЙ команды, — это уже не
 инвариант класса, а её постусловие. Инвариант агрегата один и живёт в `checkInvariants`;
 отдельный метод проверки уместен, когда у корня несколько независимых групп правил и
 гонять их все на каждой команде дорого.
 */
@attached(body)
public macro Invariant<Root>(check: (Root) -> () -> Void) =
    #externalMacro(module: "CoreMacros", type: "InvariantMacro")
