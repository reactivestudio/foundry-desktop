/**
 Корень агрегата — общий словарь тактического DDD. Граница согласованности и
 единственная точка входа изменений (снаружи в части агрегата не лезут в обход него).
 Плоский вариант — БЕЗ доменных событий; агрегатам, которым события нужны, служит
 наследник `DispatchingAggregateRoot` (протокол `Dispatchable`).

 Инварианты: `checkInvariants` переопределяет конкретный корень (в Swift нет `abstract`,
 базовый — пустой no-op). Автоматически повесить проверку на каждый публичный метод
 нельзя (в Swift нет AOP/аспектов), поэтому все команды идут через `mutate { … }` —
 единую точку мутации, которая сама зовёт `checkInvariants` после изменения: так
 проверку невозможно забыть.

 `open`-класс, напрямую не инстанцируется по соглашению. Один тип — один файл.
 */
open class AggregateRoot<ID: Hashable>: Entity<ID> {
    /**
     Проверка кросс-групповых инвариантов; переопределяется корнем. Зовётся автоматически
     из `mutate` после каждого изменения. НЕ `throws` намеренно: нарушение инварианта —
     ошибка кода (аналог Kotlin `check()` = unchecked → `precondition`, краш), а
     восстановимую валидацию входа делают фабрики через `require` (аналог Kotlin
     `require()` = checked `throws`).
     */
    open func checkInvariants() {}

    /**
     Выполнить изменение и сразу проверить инварианты — единая точка мутации. Непадающая
     намеренно: всю восстановимую валидацию команда делает ДО `mutate` (строит уже
     валидный под-VO через `try …`), а `mutate` лишь присваивает готовое и проверяет
     инварианты. Отсюда два свойства: на вызове `mutate` НИКОГДА нет `try` (единообразно
     во всех командах) и мутация не может применить полусостояние.
     */
    public func mutate(on change: () -> Void) {
        change()
        checkInvariants()
    }
}
