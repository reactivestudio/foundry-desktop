import Core
import SwiftUI

/**
 Начертания эталона, которых канон не называет.

 Всё, что канон называет, берётся у него прямо: проза это `body`, акцент
 в прозе — `bodyEm`, мета и подписи — `caption`, лейбл секции — `label`.
 Здесь остаются ШЕСТЬ отклонений, каждое снято пробой с принятого кадра.
 Список короткий намеренно: он и есть вопрос эталона к канону — либо канон
 заводит эти веса у себя, либо экран приводится к канону. Пока вопрос
 не решён, отклонения живут в одном месте и наперечёт, а не тройками
 по телам вью.
 */
enum BoardType {
    /// Имя окна и невыбранная вкладка пайплайна: та же проза, но полужирнее.
    /// Полужирный набор без ступени цвета отличал бы их от выбранного слишком
    /// слабо, а ступень цвета без веса — слишком грубо.
    static let bodyMedium = TypeToken(size: 13, leading: 18, weight: .medium, family: .text)
    /// Сочетание клавиш рядом с действием. Не моноширинное: клавиша — не код.
    static let key = TypeToken(size: 11, leading: 14, weight: .medium, family: .text)
    /// Счётчик на вкладке пайплайна: он живёт в пилюле, и внутри неё вес
    /// работает вместо размера.
    static let pipeCount = TypeToken(size: 11, leading: 14, weight: .bold, family: .text)
    /// Подпись стадии над числом. Строчными и без разрядки: ряд шапок капсом
    /// смешивал алфавиты в одной строке — QUESTIONS … ГОТОВО.
    static let columnName = TypeToken(size: 11, leading: 14, weight: .medium, family: .text)
    /// Чип состояния. Разрядка полпроцента — набор внутри сплошной заливки
    /// плотнее, чем на фоне.
    static let chip = TypeToken(
        size: 11, leading: 14, weight: .semibold, family: .text,
        tracking: 0.005)
    /// Слово под знаком в рейле: разрядка процент, чтобы слово шириной
    /// в подложку не слипалось.
    static let railLabel = TypeToken(
        size: 11, leading: 14, weight: .regular, family: .text,
        tracking: 0.01)
}
