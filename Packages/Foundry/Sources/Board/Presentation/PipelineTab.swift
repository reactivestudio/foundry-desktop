import Foundation

/**
 Вкладка пайплайна над доской.

 Число несёт КАЖДАЯ вкладка, у которой есть работа, включая выбранную:
 пока выбранная числа не носила, сумма на экране не сходилась — счётчик
 проекта не с чем было сложить, а число соседней вкладки стояло в том же
 слоте, что «8 стадий» у выбранной, и честно читалось как число стадий.
 Теперь слот один и тот же у всех, а длина пайплайна ушла в подпись.

 Ноль на вкладке не пишется вовсе: ноль — не величина, а её отсутствие.
 На пустом проекте экран печатал семнадцать нулей, и приглашение завести
 первый change конкурировало по площади с семнадцатью повторами одного факта.
 */
struct PipelineTab: Identifiable, Sendable {
    let id = UUID()
    let name: String
    /// Стадии пайплайна. Пайплайны РАЗНОЙ длины, и это значимая информация,
    /// а не дефект вёрстки.
    let stages: [String]
    /// Сколько change'ей проекта идёт по этому пайплайну. Не `count`: это
    /// не размер набора у вкладки на руках, а величина предметной области,
    /// и слово `count` рядом с нулём читалось бы пустотой коллекции.
    let changes: Int

    init(_ name: String, _ stages: [String], _ changes: Int) {
        self.name = name
        self.stages = stages
        self.changes = changes
    }

    /// Число вкладки, каким его печатают, — или ничего. Ноль отсутствует
    /// здесь, а не в вёрстке: решение «ноль не пишется» принадлежит вкладке,
    /// и вид не должен принимать его заново каждым `if`.
    var countText: String? { changes == 0 ? nil : String(changes) }

    /// «8 стадий», «3 стадии» — подпись стоит только у выбранной вкладки.
    var stagesText: String {
        let n = stages.count
        let word = (2...4).contains(n % 10) && !(12...14).contains(n % 100) ? "стадии" : "стадий"
        return "\(n) \(word)"
    }
}
