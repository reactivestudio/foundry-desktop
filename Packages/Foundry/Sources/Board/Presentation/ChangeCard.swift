import Foundation

/**
 Карточка change'а — модель ПРЕЗЕНТАЦИИ, не домена.

 Своей доменной модели у доски пока нет вовсе: экран принят эталоном раньше,
 чем появились сущности, и всё, что здесь лежит, — снимок того, что видно
 на кадре. Когда придёт настоящий `Change`, эта структура умрёт целиком
 и заменится проекцией из Application-слоя — она для того и держится
 в презентации, чтобы умереть без следа.

 Полей ровно столько, сколько рисует карточка. Ни вида, ни ветки здесь нет:
 знак вида дублировал префикс ветки и отъедал 18 пунктов у заголовка в дорожке
 шириной 124, а сама ветка на восемнадцати карточках была транслитерацией
 собственного заголовка. То и другое живёт в инспекторе — и приедет сюда
 вместе с ним, а не в запас.
 */
struct ChangeCard: Identifiable, Sendable {
    let id = UUID()
    let title: String
    let move: ChangeMove
    /// Подпись чипа: «ждёт 26 ч», «идёт 18 мин», «встало 6 ч», «упало 3 ч».
    /// В корзине «Готово» — время приёмки: «вчера, 14:32».
    let sinceText: String

    init(_ title: String, _ move: ChangeMove, _ sinceText: String) {
        self.title = title
        self.move = move
        self.sinceText = sinceText
    }
}
