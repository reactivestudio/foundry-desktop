/**
 Порт показа инструкции по установке инструмента. Кнопка Install в мастере НИЧЕГО не
 устанавливает: приложение не ставит за пользователя чужие CLI (у каждого свой менеджер
 пакетов, своя аутентификация и своя сеть) и не имитирует установку — оно ведёт туда, где
 написано, как поставить. Установленность приложение потом просто ЗАМЕЧАЕТ (`ToolGateway`),
 когда пользователь вернётся в окно.

 Отдельный порт, а не метод `ToolGateway`: там опрос системы, здесь показ страницы
 пользователю — разные механизмы (процессы против `NSWorkspace`) и разные акторы.
 `@MainActor`: открытие бьёт по AppKit. Продакшн-адаптер — `WebInstallInstructions`.
 */
public protocol InstallInstructionOpening: Sendable {
    @MainActor func openInstructions(for tool: ToolId)
}
