/**
 Порт разрешений ОС: спросить состояние и попросить доступ. Это ЕДИНСТВЕННАЯ дверь BC
 `Setting` к системным механизмам разрешений — ни сценарий, ни вью не зовут
 `UNUserNotificationCenter`/`AXIsProcessTrusted` сами, иначе домен зависел бы от AppKit
 и от того, чем macOS проверяет доступ в этом релизе.

 Не репозиторий: за портом не хранилище наших данных, а чужая истина, которую нельзя
 сохранить (разрешение отзывают мимо приложения) — потому `Permission` только читают.

 Асинхронный: системный диалог показывается пользователю, и ответ приходит не сразу.
 `Sendable` — порт зовут с главного актора, а исполняет его системный механизм.
 Продакшн-адаптер — `SystemPermissionGateway` в Infrastructure; тест подставляет заглушку
 и проходит сценарий, не показывая ни одного диалога.
 */
public protocol PermissionGateway: Sendable {
    /// Текущее состояние вида разрешения. Вопрос без последствий: диалогов не показывает.
    func status(of kind: PermissionKind) async -> PermissionStatus

    /// Попросить доступ у системы и вернуть состояние ПОСЛЕ ответа. Для видов, которые
    /// macOS выдаёт не в диалоге, а в Системных настройках, состояние может остаться
    /// прежним — доступ появится позже, и его увидит следующий `status(of:)`.
    func request(kind: PermissionKind) async -> PermissionStatus
}
