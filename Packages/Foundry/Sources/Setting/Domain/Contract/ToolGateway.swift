/**
 Порт связки с инструментами: спросить систему, стоит ли инструмент и какой он версии.
 Единственная дверь BC `Setting` к тому, что лежит на диске пользователя, — ни сценарий,
 ни вью не ищут исполняемые файлы сами и не знают ни про PATH, ни про `--version`.

 Какой файл или каталог стоит за инструментом — деталь адаптера: домен оперирует id
 инструмента, а не именем бинаря. Ставить инструменты порт не умеет намеренно: сегодня
 приложение никого не устанавливает, оно показывает, чего не хватает, и ведёт к инструкции
 (порт `InstallInstructionOpening`). Появится своя установка — появится и своя дверь.

 Асинхронный: за ответом поход на диск и запуск чужого процесса. Продакшн-адаптер —
 `CommandLineToolGateway`; тест подставляет заглушку и не трогает ни диск, ни процессы.
 */
public protocol ToolGateway: Sendable {
    func inspect(tool: ToolId) async -> Installation
}
