import Core

/**
 Вид разрешения ОС, которое приложению приходится просить у macOS. Домен знает ровно
 то, что ему нужно решать: КАКОЕ разрешение обсуждается. Каким системным механизмом
 оно спрашивается (`UNUserNotificationCenter`, `AXIsProcessTrusted`) — деталь адаптера
 за портом `PermissionGateway`, сюда она не течёт.

 Порядок объявления — порядок строк на экране разрешений (`CaseIterable`): сперва
 уведомления, потом универсальный доступ, как в принятом прототипе. Один тип — один файл.
 */
public enum PermissionKind: ValueObject, CaseIterable {
    /// Показывать уведомления о ходе стадий.
    case notifications
    /// Универсальный доступ: глобальный шорткат и панель у чёлки.
    case accessibility
}
