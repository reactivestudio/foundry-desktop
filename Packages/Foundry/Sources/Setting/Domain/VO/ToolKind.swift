import Core

/**
 Вид инструмента. Агрегат `Tool` один на все инструменты, а различает их вид: у каждого
 своя роль в связке и свой способ проверки установки.

 Ровно три вида, и это не задел на будущее, а нынешний состав связки: агент, который
 пишет код; плагин, который учит агента стадиям; и `foundry` CLI, который эти стадии
 детерминированно гоняет. Один тип — один файл.
 */
public enum ToolKind: ValueObject, CaseIterable {
    /// CLI агента на выбор: Claude Code, Codex, Gemini.
    case agentCli
    /// Плагин агента — стадии и навыки для выбранного CLI.
    case agentPlugin
    /// Собственный CLI Foundry — прослойка детерминированного управления стадиями.
    case foundryCli
}
