import Core

/**
 Состояние разрешения ОС глазами приложения. Три положения, а не булев флаг: «ещё не
 спрашивали» и «отказано» ведут себя по-разному — первое лечится вопросом, второе только
 походом пользователя в Системные настройки, и экран обязан их различать.

 Значение НЕ хранится: истина о разрешениях живёт в ОС, приложение её только читает через
 порт. Потому статуса и нет в агрегате `Preference` — сохранённая копия неминуемо разошлась
 бы с системой (разрешение отзывают мимо нас). Один тип — один файл.
 */
public enum PermissionStatus: ValueObject {
    /// Ещё не спрашивали — вопрос уместен.
    case notDetermined
    /// Разрешено.
    case granted
    /// Отказано; повторный вопрос система уже не покажет.
    case denied
}
