/// Стереотип-бин слоя **Domain** — доменная служба DDD: правило, которое не садится ни на одну
/// сущность и ни на один агрегат (политика поверх НЕСКОЛЬКИХ агрегатов, расчёт, которому нужны данные
/// со стороны). Именно бизнес-правило, а не оркестрация: транзакций не открывает, портов
/// инфраструктуры не знает — только доменные контракты.
///
/// Отличие от [`ApplicationService`] жёсткое: доменная служба ОТВЕЧАЕТ НА ВОПРОС «как правильно по
/// правилам предметной области», прикладная — «в каком порядке дёрнуть участников, чтобы выполнить
/// сценарий». Тянет к оркестрации, портам, транзакции — это `@ApplicationService`, не сюда.
/// Не находится правила поверх нескольких агрегатов — скорее всего метод просто принадлежит агрегату.
///
/// Не Spring-стереотип: там всё это один `@Service` без различения слоя. Мы делим сознательно, как и
/// с [`Store`] вместо `@Controller`, — точность DDD дороже буквальности Spring. Скан подхватывает
/// наравне с `@Component`; определение бина генерит `BeanScan`. Скоуп — `singleton` по умолчанию.
