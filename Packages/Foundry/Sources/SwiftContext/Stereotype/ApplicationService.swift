/// Стереотип-бин слоя **Application** — прикладная служба: оркестрирует сценарии поверх портов
/// (репозитории, шлюзы), СОБСТВЕННЫХ бизнес-правил не имеет — они в агрегатах и доменных службах.
/// Она же граница согласованности: один вызов = один атомарный переход (у нас без БД — «прочитать
/// актуальное, применить, сохранить целиком»).
///
/// Сценариев в одном типе может быть несколько (тогда это именно `@ApplicationService`); ровно один —
/// пиши [`UseCase`], частный случай этой же роли. Бизнес-правило вместо порядка вызовов —
/// [`DomainService`].
///
/// Не Spring-стереотип: там на всё это один `@Service`, слоя он не различает. Делим сознательно —
/// точность DDD дороже буквальности Spring (как [`Store`] вместо `@Controller`). Скан подхватывает
/// наравне с `@Component`; определение бина генерит `BeanScan`. Скоуп — `singleton` по умолчанию.
@attached(peer)
public macro ApplicationService(name: String? = nil, scope: Scope = .singleton) =
    #externalMacro(module: "SwiftContextMacros", type: "ComponentMacro")
