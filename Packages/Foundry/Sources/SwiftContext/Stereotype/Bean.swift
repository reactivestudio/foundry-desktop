/// Метод-фабрика бина внутри `@Configuration` (аналог `@Bean` Spring). Сам по себе ничего
/// не разворачивает — это маркер, который читает `@Configuration`: он и генерит регистрацию
/// по возвращаемому типу метода. Метод остаётся обычным — `@Configuration` зовёт его при
/// сборке контейнера, подставляя параметры резолвом из контейнера. `name` задаёт имя бина
/// (иначе — имя метода, как в Spring).
///
/// ВАЖНО про тип: `targetTypes` бина = РОВНО объявленный тип возврата, без замыкания супертипов.
/// Асимметрия с `@Component` (тому замыкание считает скан по всему исходнику) неустранима: макрос
/// видит только своё объявление, цепочку наследования чужого типа ему не узнать. Spring тут шире —
/// он добирает супертипы рефлексией. Практическое правило: **объявляй в возврате тот тип, по
/// которому будешь резолвить** (обычно — контракт, а не реализацию), как и принято для `@Bean`.
