/**
 `ConfigurableApplicationContext` — контекст с властью над жизненным циклом (точное имя и роль из
 Spring: там этот интерфейс отделён от `ApplicationContext` ровно затем, чтобы `refresh`/`close` были
 доступны тому, кто контейнер СОБРАЛ, а не всякому, кому его дали почитать).

 Владелец — корень композиции: он один вызывает `refresh` (обычно из конструктора) и `close` на
 сворачивании. Всем остальным достаётся `ApplicationContext` — только чтение.
 */
public protocol ConfigurableApplicationContext: ApplicationContext {
    /// Собрать контекст: зарегистрировать окружение и определения бинов, затем жадно
    /// преинстанциировать синглтоны (аналог `AbstractApplicationContext.refresh`).
    func refresh() throws

    /// Свернуть контекст: уничтожить синглтоны (`DisposableBean.destroy` на тех, кто его реализует)
    /// в порядке, обратном созданию, — зависимость обязана переживать своего зависящего. После этого
    /// контекст неактивен, и резолв из него — ошибка, а не полуразрушенный бин.
    func close()
}
