/// Бин, которому есть что отпустить на сворачивании контекста (точное имя из Spring —
/// `DisposableBean`): закрыть файл, погасить наблюдателя, отменить задачу. Контейнер зовёт `destroy`
/// на `close()` в порядке, ОБРАТНОМ созданию, — зависимость гасится после того, кто ею пользовался.
///
/// Ошибку из `destroy` контейнер не роняет наружу: сворачивание обязано дойти до конца и погасить
/// остальных — иначе первый спотыкнувшийся бин утащил бы за собой утечку всех последующих.
public protocol DisposableBean {
    func destroy() throws
}
