/// Порт импорта ран-сессии во внешний просмотрщик агента. `RunStore`
/// (презентационный стор) не должен сам дотягиваться до AppKit/NSWorkspace: побочный эффект
/// «показать сессию снаружи» инвертирован в этот порт, а конкретный адаптер
/// внедряется из корня композиции. Как именно открывается сессия (deep link,
/// схема, целевое приложение) — деталь адаптера, порт про это не знает. Сегодня
/// продакшн-реализация — `ClaudeDesktopSessionOpener` в Infrastructure. Тест
/// подставляет шпион и проверяет ветку импорта, не открывая настоящее приложение.
public protocol AgentSessionOpening: Sendable {
    /// Импортировать сессию, когда её транскрипт появится на диске (гонка с
    /// созданием транскрипта после system/init разрешается ожиданием файла).
    /// Автоимпорт при старте рана.
    func openSession(sessionID: String, projectDirectory: String) async

    /// Открыть сессию немедленно — по кнопке в карточке результата, когда ран уже
    /// завершён и транскрипт заведомо на диске. Ждать файла не нужно. На главном
    /// акторе: открытие бьёт по AppKit (`NSWorkspace`), это UI-работа.
    @MainActor func openSessionNow(sessionID: String)
}
